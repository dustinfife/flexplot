// Reproducible source fingerprint and archive/installed payload verification.
// Uses only Node built-ins and the compiler's existing JSZip dependency.
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const sha=data=>crypto.createHash('sha256').update(data).digest('hex');
function walk(root,relative='') {
 if(!fs.existsSync(path.join(root,relative)))return [];
 return fs.readdirSync(path.join(root,relative),{withFileTypes:true}).sort((a,b)=>a.name.localeCompare(b.name,'en')).flatMap(entry=>{
  const name=path.posix.join(relative,entry.name);
  return entry.isDirectory()?walk(root,name):entry.isFile()?[name]:[];
 });
}
function source(root) {
 const files=['DESCRIPTION','NAMESPACE','.Rbuildignore',...['R','jamovi','data','inst','man','vignettes'].flatMap(dir=>walk(root,dir))]
  .filter(name=>fs.existsSync(path.join(root,name)))
  .filter(name=>!/^R\/scratch\//.test(name) && !/^R\/(.*\.h\.R|00jmv\.R)$/.test(name))
  .filter(name=>!/^inst\/i18n\//.test(name)) // regenerated by the compiler
  .sort();
 const entries=files.map(name=>[name,sha(fs.readFileSync(path.join(root,name)))]);
 return {algorithm:'sha256',scope:'package-and-jamovi-build-inputs-v1',fingerprint:sha(JSON.stringify(entries)),files:entries};
}
async function payload(archive,installed,compiler) {
 const JSZip=require(require.resolve('jszip',{paths:[compiler]}));
 const raw=fs.readFileSync(archive),zip=await JSZip.loadAsync(raw),entries=[];
 for(const name of Object.keys(zip.files).sort()) {
  if(zip.files[name].dir)continue;
  if(!name.startsWith('flexplot/') || name.split('/').includes('..'))throw Error('Unsafe module archive entry');
  const relative=name.slice('flexplot/'.length),data=await zip.files[name].async('nodebuffer');
  const target=path.join(installed,relative);
  if(!fs.existsSync(target) || sha(fs.readFileSync(target))!==sha(data))throw Error('Installed payload mismatch: '+relative);
  entries.push([relative,sha(data)]);
 }
 return {archive_sha256:sha(raw),payload_sha256:sha(JSON.stringify(entries)),files:entries};
}
module.exports={source,payload};
if(require.main===module)(async()=>{
 const [mode,root,...args]=process.argv.slice(2);
 const result=mode==='source'?source(root):await payload(root,...args);
 process.stdout.write(JSON.stringify(result)+'\n');
})().catch(error=>{console.error(error.message);process.exitCode=1;});
