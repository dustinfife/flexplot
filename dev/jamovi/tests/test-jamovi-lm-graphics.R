test_that("removed LM graphic controls retain saved options without affecting restored fits", {
  jmvcore:::initProtoBuf()
  message = jmvcore:::RProtoBuf_new(get("jamovi.coms.AnalysisOptions",asNamespace("jmvcore")))
  template = jmvcore:::RProtoBuf_new(get("jamovi.coms.AnalysisOption",asNamespace("jmvcore")))
  saved = list(out="y",preds=c("x","a"),modelTerms=list("x","a",c("x","a")),
    quadratic="x",polynomials=TRUE,interactions=TRUE,interactionSpecVersion=1,
    compare=TRUE,comparisonTerms=list("x","a"),comparisonX="x",comparisonPanels="a",
    line="Logistic",center="Mean + stdev",se=TRUE,plotX="x",plotPanels="a")
  message$names = names(saved)
  message$options = lapply(saved,jamovi_mixed_saved_option,option_template=template,group_template=message)
  original = flexplot:::glmbasicOptions$new();original$fromProtoBuf(message)
  restored = flexplot:::glmbasicOptions$new();restored$fromProtoBuf(original$asProtoBuf())
  for (name in names(saved)) expect_equal(restored[[name]],saved[[name]])
  analysis = flexplot:::glmbasicClass$new(options=restored,data=small)
  expect_true(analysis$run())
  independent = lm(y~x*a+I(x^2),small)
  jamovi_expect_lm_coefficients(analysis,independent)
  expect_equal(coef(analysis$results$comparisonplot$state$model1),coef(independent),tolerance=1e-12)
  expect_equal(coef(analysis$results$comparisonplot$state$model2),coef(lm(y~x+a,small)),tolerance=1e-12)
  capture = new.env(parent=emptyenv())
  local_mocked_bindings(jamovi_glm_model_plot=jamovi_model_plot_recorder(capture))
  withr::local_options(device=function(...)grDevices::pdf(file=NULL))
  previous_theme = ggplot2::theme_get();withr::defer(ggplot2::theme_set(previous_theme))
  expect_warning(expect_true(analysis$.__enclos_env__$private$.plot(analysis$results$plot)),"beyond the range")
  curve = Filter(function(layer) is.data.frame(layer$data) && "prediction" %in% names(layer$data),capture$plot$layers)[[1]]$data
  expected = predict(independent,newdata=curve,interval="confidence")
  expect_equal(curve$prediction,unname(expected[,"fit"]),tolerance=1e-10)
  expect_equal(curve$prediction.lwr,unname(expected[,"lwr"]),tolerance=1e-10)
  expect_equal(curve$prediction.upr,unname(expected[,"upr"]),tolerance=1e-10)
})

test_that("restored five-predictor LM options render automatic plots and preserve inference", {
  jmvcore:::initProtoBuf()
  previous_theme = ggplot2::theme_get()
  withr::defer(ggplot2::theme_set(previous_theme))
  withr::local_pdf(file=tempfile(fileext=".pdf"))
  withr::local_seed(747)
  data = as.data.frame(matrix(rnorm(720),120,6))
  names(data) = c("y",paste0("x",1:5))
  data$x5[1:10] = NA_real_
  message = jmvcore:::RProtoBuf_new(get("jamovi.coms.AnalysisOptions",asNamespace("jmvcore")))
  template = jmvcore:::RProtoBuf_new(get("jamovi.coms.AnalysisOption",asNamespace("jmvcore")))
  saved = list(out="y",preds=paste0("x",1:5),graphic=TRUE,compare=TRUE,
    modelTerms=c(as.list(paste0("x",1:5)),list(c("x1","x2"))),
    comparisonTerms=as.list(paste0("x",1:5)),interactions=TRUE,polynomials=TRUE,quadratic="x1",comparisonX="x1")
  message$names = names(saved)
  message$options = lapply(saved,jamovi_mixed_saved_option,option_template=template,group_template=message)
  options = flexplot:::glmbasicOptions$new();options$fromProtoBuf(message)
  analysis = flexplot:::glmbasicClass$new(options=options,data=data)
  expect_true(analysis$run())
  expect_true(analysis$.__enclos_env__$private$.plot(analysis$results$plot))
  reopened = flexplot:::glmbasicOptions$new();reopened$fromProtoBuf(options$asProtoBuf())
  restored = flexplot:::glmbasicClass$new(options=reopened,data=data)
  expect_true(restored$run())
  expect_null(reopened$plotX)
  expect_identical(reopened$modelTerms,options$modelTerms)
  expect_identical(reopened$comparisonTerms,options$comparisonTerms)
  expect_identical(reopened$quadratic,"x1")
  expect_true(restored$.__enclos_env__$private$.plot(restored$results$plot))
  expect_true(restored$.__enclos_env__$private$.comparisonplot(restored$results$comparisonplot))
  model = stats::lm(y~x1+x2+x3+x4+x5+x1:x2+I(x1^2),data=data)
  jamovi_expect_lm_coefficients(restored,model)
  expect_equal(stats::nobs(restored$results$comparisonplot$state$model1),110)
  expect_true(jamovi_reporting_update(restored,list(se=FALSE)))
  expect_true(restored$.__enclos_env__$private$.plot(restored$results$plot))
  jamovi_expect_lm_coefficients(restored,model)
})

test_that("restored invalid LM layouts produce completed diagnostic images on the E2E fixture", {
  jmvcore:::initProtoBuf()
  source(file.path(root,"dev/jamovi/e2e/fixtures.R"),local=TRUE)
  data = e2e_fixtures()$primary
  message = jmvcore:::RProtoBuf_new(get("jamovi.coms.AnalysisOptions",asNamespace("jmvcore")))
  template = jmvcore:::RProtoBuf_new(get("jamovi.coms.AnalysisOption",asNamespace("jmvcore")))
  saved = list(out="y",preds=c("x","group"),modelTerms=list("x","group"),
    mainEffects=c("x","group"),plotPanels="group",plotGroup="x",graphic=TRUE)
  message$names = names(saved)
  message$options = lapply(saved,jamovi_mixed_saved_option,option_template=template,group_template=message)
  options = flexplot:::glmbasicOptions$new();options$fromProtoBuf(message)
  reopened = flexplot:::glmbasicOptions$new();reopened$fromProtoBuf(options$asProtoBuf())
  analysis = flexplot:::glmbasicClass$new(options=reopened,data=data)
  output = withr::local_tempdir()
  analysis$.setResourcesPathSource(function(name,ext)list(rootPath=output,relPath=paste0(name,".",ext)))
  previous_theme = ggplot2::theme_get();withr::defer(ggplot2::theme_set(previous_theme))
  expect_true(analysis$run())
  image = analysis$results$plot
  expect_null(reopened$plotX)
  expect_identical(reopened$plotPanels,"group")
  expect_identical(reopened$plotGroup,"x")
  expect_true(suppressWarnings(analysis$.createImage(".plot",image,noThrow=TRUE)))
  error = image$asProtoBuf(status=3L,includeState=FALSE)
  expect_equal(error$status,4L)
  records = list(list(status=error$status,image=list(path=error$image$path,width=error$image$width,height=error$image$height)))
  expect_gt(file.info(file.path(output,image$filePath))$size,1000)
  jamovi_expect_lm_coefficients(analysis,lm(y~x+group,data))
  expect_true(jamovi_reporting_update(analysis,list(plotGroup=NULL)))
  expect_null(image$filePath)
  expect_true(analysis$.createImage(".plot",image,noThrow=TRUE))
  expect_identical(image$status,"complete")
  jamovi_expect_lm_coefficients(analysis,lm(y~x+group,data))
  complete = image$asProtoBuf(status=3L,includeState=FALSE)
  records[[2]] = list(status=complete$status,image=list(path=complete$image$path,width=complete$image$width,height=complete$image$height))
  file = withr::local_tempfile(fileext=".json")
  jsonlite::write_json(records,file,auto_unbox=TRUE)
  runtime = Sys.glob("/Applications/jamovi.app/Contents/Resources/jamovi/client/dist/assets/resultsview-*.js")
  log = system2(Sys.which("node"),shQuote(c(test_path("js","jamovi-lm-image-renderer.cjs"),runtime,file)),stdout=TRUE,stderr=TRUE)
  expect_null(attr(log,"status"),info=paste(log,collapse="\n"))
  expect_match(paste(log,collapse="\n"),"without a running indicator",fixed=TRUE)
})
